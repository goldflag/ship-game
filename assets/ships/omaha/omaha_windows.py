def _strips(kind, u0, u1):
    """A window's run across the view in strips of about STRIP; a scuttle whole."""
    if kind != 'w':
        return [(u0, u1)]
    n = max(1, round((u1 - u0) / STRIP))
    return [(u0 + (u1 - u0) * k / n, u0 + (u1 - u0) * (k + 1) / n) for k in range(n)]


def _openings():
    """(window key, kind, corner rays [(origin, direction)], expected wall point, (width, height)); windows in strips."""
    for rows, sign, view in ((PORT, -1, 'port'), (STARBOARD, 1, 'starboard')):
        d = Vector((0, -1 if sign < 0 else 1, 0))  # authoring +Y is port: rays run inboard
        for i, (kind, z0, z1, y0, y1, wx) in enumerate(rows):
            for a, b in _strips(kind, z0, z1):
                corners = [(Vector(P(sign * 60, y, z)), d) for z, y in ((a, y0), (b, y0), (b, y1), (a, y1))]
                yield (view, i), kind, corners, Vector(P(wx, (y0 + y1) / 2, (a + b) / 2)), (b - a, y1 - y0)
    for rows, sign, view in ((FRONT, -1, 'front'), (AFT, 1, 'aft')):
        d = Vector((-1 if sign < 0 else 1, 0, 0))
        for i, (kind, x0, x1, y0, y1, wz) in enumerate(rows):
            for a, b in _strips(kind, x0, x1):
                corners = [(Vector(P(x, y, sign * 150)), d) for x, y in ((a, y0), (b, y0), (b, y1), (a, y1))]
                yield (view, i), kind, corners, Vector(P((a + b) / 2, (y0 + y1) / 2, wz)), (b - a, y1 - y0)


def _plate(outline, n, proud, sunk):
    """A closed plate from an outline in the wall plane: its face `proud` in front of the wall, its back `sunk` into it."""
    front = [p + n * proud for p in outline]
    back = [p - n * sunk for p in outline]
    k = len(outline)
    faces = [tuple(range(k)), tuple(k + i for i in reversed(range(k)))] + [(i, k + i, k + (i + 1) % k, (i + 1) % k) for i in range(k)]
    return front + back, faces


def _ring(hit, n, r, sides=14):
    """Points of a circle of radius r about `hit` in the plane normal to n."""
    a = Vector((0, 0, 1)).cross(n)
    if a.length < .2:
        a = Vector((1, 0, 0)).cross(n)
    a.normalize()
    b = n.cross(a)
    return [hit + r * (a * math.cos(math.tau * i / sides) + b * math.sin(math.tau * i / sides)) for i in range(sides)]


class _Merged:
    def __init__(self):
        self.vv, self.ff = [], []

    def add(self, v, f):
        base = len(self.vv)
        self.vv += [tuple(p) for p in v]
        self.ff += [tuple(base + i for i in face) for face in f]


def build(D, kit):
    tree = kit.support.tree
    found, skipped = [], 0
    for key, kind, corners, expect, (w, h) in _openings():
        o = sum((c[0] for c in corners), Vector()) / 4
        d = corners[0][1]
        hit, n, index, _ = tree.ray_cast(o, d, 300)
        tolerance = TOLERANCE if kind == 's' else WINDOW_TOLERANCE
        if hit is None or (hit - expect).dot(d) ** 2 > tolerance ** 2:
            skipped += 1
            continue
        n = n.normalized()
        if n.dot(d) > 0:
            n = -n
        facing = -n.dot(d)
        if facing < .35:
            skipped += 1
            continue
        if kind == 'w':
            outline = [oc + dc * ((hit - oc).dot(n) / dc.dot(n)) for oc, dc in corners]
        else:
            outline = _ring(hit, n, RIM, 8)
        # The opening's own outline must lie on the wall: every point finds the wall within 6 cm. A window strip
        # across a facet's edge fails and leaves a gap, as a mullion would.
        if any(tree.ray_cast(p + n * .1, -n, .16)[0] is None for p in outline):
            skipped += 1
            continue
        found.append((facing, key, kind, hit, (w, h), outline, n, index < kit.hull_face_count))
    # An opening seen in two views (a canted face) is glazed once, from the view that faces it best; the strips of
    # one window never displace each other.
    kept = []
    for f in sorted(found, key=lambda f: -f[0]):
        _, key, kind, hit, (w, h) = f[:5]
        if kind == 's':
            clash = any(k[2] == 's' and (hit - k[3]).length < .6 * max(w, h, *k[4]) for k in kept)
        else:
            clash = any(k[2] == 'w' and k[1] != key and (hit - k[3]).length < .75 * max(w, k[4][0]) + .02 for k in kept)
        if not clash:
            kept.append(f)
    panes, rims, glass = _Merged(), {True: _Merged(), False: _Merged()}, {True: _Merged(), False: _Merged()}
    for _, _, kind, hit, size, outline, n, on_hull in kept:
        if kind == 'w':
            panes.add(*_plate(outline, n, PROUD, SUNK))
            continue
        rims[on_hull].add(*_plate(_ring(hit, n, RIM), n, .03, .01))
        glass[on_hull].add(*_plate(_ring(hit, n, GLASS), n, .036, 0))
    col = kit.collections['Superstructure']
    if panes.vv:
        kit.tag(kit.mesh('bridge-glazing.window glass', panes.vv, panes.ff, 'glass', col), 'bridge-glazing')
    for on_hull, assembly in ((True, 'hull-scuttles'), (False, 'superstructure-scuttles')):
        c = kit.collections['Hull and decks'] if on_hull else col
        if rims[on_hull].vv:
            kit.tag(kit.mesh(assembly + '.scuttle rim', rims[on_hull].vv, rims[on_hull].ff, 'naval', c), assembly)
            kit.tag(kit.mesh(assembly + '.scuttle glass', glass[on_hull].vv, glass[on_hull].ff, 'glass', c), assembly)
    windows = len({f[1] for f in kept if f[2] == 'w'})
    strips = sum(1 for f in kept if f[2] == 'w')
    scuttles = sum(1 for f in kept if f[2] == 's')
    print('Omaha glazing:', windows, 'windows in', strips, 'strips and', scuttles, 'scuttles;', len(found) - len(kept), 'duplicates,', skipped, 'left out')
